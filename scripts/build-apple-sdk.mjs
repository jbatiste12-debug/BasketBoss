// Reproducible official SDK packaging for Pages' ESM-only runtime. The SDK is
// evaluated only by the existing request-time dynamic import in our loader.
import fs from 'node:fs';
import path from 'node:path';
import {builtinModules,createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const SDK_VERSION='3.1.0',ESBUILD_VERSION='0.28.2';
const builtins=new Set(builtinModules.map(name=>name.replace(/^node:/,'')));
export function appleBuiltinFacades(){
 return {name:'apple-sdk-native-builtins',setup(builder){
  builder.onResolve({filter:/.*/},args=>{
   const name=args.path.replace(/^node:/,'');if(!builtins.has(name))return;
   if(args.namespace==='apple-sdk-builtin')return {path:'node:'+name,external:true};
   return {path:name,namespace:'apple-sdk-builtin'};
  });
  builder.onLoad({filter:/.*/,namespace:'apple-sdk-builtin'},args=>({loader:'js',contents:'import * as native from '+JSON.stringify('node:'+args.path)+'; module.exports = native.default ?? native;'}));
 }};
}
export function appleWorkersFetch(directory=root){
 return {name:'apple-sdk-workers-fetch',setup(builder){
  builder.onResolve({filter:/^node-fetch$/},()=>({path:path.join(directory,'bb-server-lib/bb-apple-fetch.js')}));
 }};
}
function licenseFiles(inputs,directory){
 const packages=new Map();
 for(const input of Object.keys(inputs)){
  if(input.includes('apple-sdk-builtin:'))continue;
  let at=path.dirname(path.resolve(directory,input));
  for(;;){
   const candidate=path.join(at,'package.json');
   if(fs.existsSync(candidate)){
    const pkg=JSON.parse(fs.readFileSync(candidate,'utf8'));
    if(pkg.name&&at.includes('node_modules'))packages.set(pkg.name,{directory:at,name:pkg.name,version:pkg.version});
    break;
   }
   const parent=path.dirname(at);if(parent===at)break;at=parent;
  }
 }
 const parts=[];
 for(const pkg of [...packages.values()].sort((a,b)=>a.name<b.name?-1:a.name>b.name?1:0)){
  const names=fs.readdirSync(pkg.directory).filter(name=>/^(?:licen[cs]e|copying)(?:\.[a-z]+)?$/i.test(name)).sort();
  parts.push('===== '+pkg.name+' '+pkg.version+' =====');
  if(!names.length){if(['jsrsasign','tr46'].includes(pkg.name)){parts.push(fs.readFileSync(path.join(directory,'bb-server-lib/vendor/'+pkg.name+'.LICENSE.txt'),'utf8').replace(/\r\n/g,'\n').trim());continue;}throw Error('A bundled package has no discoverable license: '+pkg.name);}
  for(const name of names)parts.push(fs.readFileSync(path.join(pkg.directory,name),'utf8').replace(/\r\n/g,'\n').trim());
 }
 return 'Licenses for bundled official Apple SDK and dependencies.\n\n'+parts.join('\n\n')+'\n';
}
export async function buildAppleSDK({directory=root,check=false}={}){
 const require=createRequire(path.join(directory,'package.json'));
 const manifest=JSON.parse(fs.readFileSync(path.join(directory,'package.json'),'utf8'));
 const lock=JSON.parse(fs.readFileSync(path.join(directory,'package-lock.json'),'utf8'));
 if(manifest.dependencies?.['@apple/app-store-server-library']!==SDK_VERSION||lock.packages?.['node_modules/@apple/app-store-server-library']?.version!==SDK_VERSION||require('@apple/app-store-server-library/package.json').version!==SDK_VERSION||require('esbuild/package.json').version!==ESBUILD_VERSION)throw Error('Apple SDK or esbuild version differs from the reviewed pinned version.');
 const result=await build({absWorkingDir:directory,stdin:{contents:'export const APPLE_SERVER_SDK_VERSION = "3.1.0"; export function loadAppleServerSDK(){ return require("@apple/app-store-server-library"); }',sourcefile:'apple-server-sdk-entry.mjs',resolveDir:directory,loader:'js'},bundle:true,write:false,metafile:true,format:'esm',platform:'node',target:'es2022',minify:true,legalComments:'eof',charset:'utf8',plugins:[appleWorkersFetch(directory),appleBuiltinFacades()],logLevel:'silent'});
 const externals=result.metafile.outputs[Object.keys(result.metafile.outputs)[0]].imports;
 if(externals.some(value=>!value.path.startsWith('node:')&&value.path!=='encoding'))throw Error('Unexpected external SDK dependency.');
 const files={
  'bb-server-lib/vendor/apple-server-sdk.mjs':'// Generated by scripts/build-apple-sdk.mjs; official Apple SDK '+SDK_VERSION+'; Workers-native HTTP transport; esbuild '+ESBUILD_VERSION+'.\n// Preserve this request-lazy ESM boundary. Licenses: apple-server-sdk.LICENSE.txt\n'+result.outputFiles[0].text,
  'bb-server-lib/vendor/apple-server-sdk.LICENSE.txt':licenseFiles(result.metafile.inputs,directory)
 };
 for(const [name,contents]of Object.entries(files)){
  const target=path.join(directory,name);
  if(check){if(!fs.existsSync(target)||fs.readFileSync(target,'utf8')!==contents)throw Error('Vendored Apple SDK is stale; run node scripts/build-apple-sdk.mjs.');}
  else{fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,contents);}
 }
 return {version:SDK_VERSION,esbuildVersion:ESBUILD_VERSION,files:Object.keys(files),nativeImports:externals.filter(value=>value.path.startsWith('node:')).map(value=>value.path).sort(),bytes:Buffer.byteLength(files['bb-server-lib/vendor/apple-server-sdk.mjs'])};
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 try{if(process.argv.length>3||process.argv[2]&&process.argv[2]!=='--check')throw Error('Use no arguments or --check.');console.log(JSON.stringify(await buildAppleSDK({check:process.argv[2]==='--check'})));}
 catch(error){console.error(error.message);process.exitCode=1;}
}
